"""Generate Fern prerequisite values from the compatibility declarations we ship.

Keep values below docs/ so relative Markdown includes travel with release
snapshots. This reads declarations, not installed tools or CI toolchain pins:
neither of those establishes the minimum version supported by a release.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = Path("docs/_snippets/prerequisites/values")
TEMPLATES = Path("docs/_snippets/prerequisites/templates")
LICENSE = (
    "SPDX-FileCopyrightText: Copyright (c) 2026, NVIDIA CORPORATION & AFFILIATES. All rights reserved.\n"
    "SPDX-License-Identifier: Apache-2.0"
)
HEADER = (
    "{/* "
    + LICENSE
    + "\nGenerated by just docs-prerequisites; edit source declarations or templates, then regenerate. */}\n"
)
QUOTED = r"""(?:"[^"]*"|'[^']*')"""
ATTRIBUTE = rf"\s+([A-Za-z_][\w-]*)\s*=\s*({QUOTED})"
MARKDOWN_TAG = re.compile(rf"<Markdown\b(?P<attrs>(?:{ATTRIBUTE})*)\s*/>")


def visible_markdown(text: str) -> str:
    """Exclude examples and comments from checks of reader-facing includes."""
    text = re.sub(r"(?ms)^ {0,3}(`{3,}|~{3,})[^\n]*\n.*?^ {0,3}\1[ \t]*$", "", text)
    text = re.sub(r"\{/\*.*?\*/\}|<!--.*?-->", "", text, flags=re.DOTALL)
    return re.sub(r"(`+)[^\n]*?\1", "", text)


def one(pattern: str, text: str, source: Path) -> str:
    """Fail if a declaration changes shape instead of silently retaining a floor."""
    matches = re.findall(pattern, text, re.MULTILINE)
    if len(matches) != 1:
        raise ValueError(f"{source}: expected one matching compatibility declaration, found {len(matches)}")
    return matches[0]


def minimum(requirement: str, source: Path) -> str:
    # These manifests currently declare a single inclusive runtime floor. A
    # future compound constraint needs an explicit presentation decision.
    return one(r"^>=([0-9]+(?:\.[0-9]+){1,2})$", requirement, source)


def declarations(root: Path) -> tuple[dict[str, str], dict[str, str]]:
    """Return resolver constraints and reader-facing snippet contents."""
    python_path = root / "pyproject.toml"
    python = tomllib.loads(python_path.read_text())["project"]["requires-python"]
    node_path = root / "crates/node/package.json"
    node = json.loads(node_path.read_text())["engines"]["node"]
    constraints = {"python": python, "node": node}
    values = {"python": minimum(python, python_path), "node": minimum(node, node_path)}
    for key, directory in (("claude", "claude"), ("codex", "codex"), ("pi", "pi")):
        source = root / f"crates/cli/src/agents/{directory}/mod.rs"
        text = source.read_text()
        version = one(r"^\s*minimum_version:\s*\(([0-9]+,\s*[0-9]+,\s*[0-9]+)\),", text, source)
        values[key] = ".".join(part.strip() for part in version.split(","))
        constraints[key] = ">=" + values[key]
        if key == "pi":
            verified = one(r"^\s*verified_through:\s*Some\(\(([0-9]+,\s*[0-9]+)\)\),", text, source)
            values["pi-verified"] = ".".join(part.strip() for part in verified.split(",")) + ".x"

    source = root / "integrations/openclaw/package.json"
    plugin = json.loads(source.read_text())
    tested = plugin["openclaw"]["build"]["openclawVersion"]
    if plugin["peerDependencies"]["openclaw"] != tested:
        raise ValueError(f"{source}: tested OpenClaw version and peer dependency differ")
    locked = json.loads((root / "package-lock.json").read_text())["packages"]["node_modules/openclaw"]
    if locked["version"] != tested:
        raise ValueError("OpenClaw lockfile does not match the plugin's tested host version")
    values["openclaw-tested"] = tested
    # Preserve the host's full engine constraint, rather than mistaking its
    # first lower bound for support of all newer Node.js major versions.
    values["openclaw-node"] = " or ".join(f"`{part.strip()}`" for part in locked["engines"]["node"].split("||"))
    return constraints, values


def generated(root: Path) -> dict[Path, str]:
    constraints, values = declarations(root)
    # Fern inserts the snippet's final newline into its parent Markdown.
    # Keep adjoining punctuation inside the expansion to avoid rendering a
    # space before commas and periods in prose. Between words, use a space
    # suffix; Fern treats an empty string parameter as missing.
    files = {OUTPUT / f"{key}.mdx": HEADER + value + "{{suffix}}\n" for key, value in values.items()}
    files[OUTPUT / "requirements.json"] = (
        json.dumps({"$comment": LICENSE + "\nGenerated by just docs-prerequisites.", **constraints}, indent=2) + "\n"
    )
    # Fern expands Markdown snippets before parsing tables. Inlining an
    # included value therefore splits a row at the fragment's newlines. Render
    # whole tables from authored templates, using the same source values.
    for template in sorted((root / TEMPLATES).glob("*.mdx")):
        text = template.read_text()
        text = re.sub(r"^\{/\*.*?\*/\}\s*", "", text, count=1, flags=re.DOTALL)

        def substitute(match: re.Match[str]) -> str:
            key = match[1]
            if key not in values:
                raise ValueError(f"{template}: unknown prerequisite {key!r}")
            return values[key]

        files[OUTPUT / template.name] = HEADER + re.sub(r"\{\{([^}]+)\}\}", substitute, text)
    return files


def check_includes(root: Path) -> list[str]:
    """Check relative snippet paths before Fern expands them for rendering."""
    root = root.resolve()
    errors = []
    docs = (root / "docs").resolve()
    for page in docs.rglob("*.mdx"):
        text = visible_markdown(page.read_text())
        if not page.is_relative_to(docs / "_snippets") and re.search(r"\{\{\s*[\w-]+\s*\}\}", text):
            errors.append(f"{page.relative_to(root)}: unexpanded prerequisite placeholder outside a snippet")
        if re.search(r"^\|.*<Markdown", text, re.MULTILINE):
            errors.append(f"{page.relative_to(root)}: include a complete table instead of snippets in table cells")
        # Inspect every opening component, including forms our static subset
        # cannot interpret. Silently skipping a JSX expression or unfamiliar
        # attribute order would let broken requirement includes pass CI.
        for start in re.finditer(r"<Markdown\b", text):
            match = MARKDOWN_TAG.match(text, start.start())
            if match is None:
                errors.append(f"{page.relative_to(root)}: unsupported Markdown include; use static quoted attributes")
                continue
            pairs = [(attr[1], attr[2][1:-1]) for attr in re.finditer(ATTRIBUTE, match["attrs"])]
            attributes = dict(pairs)
            if len(attributes) != len(pairs) or not attributes.get("src"):
                errors.append(f"{page.relative_to(root)}: Markdown include requires one unambiguous src attribute")
                continue
            source = attributes["src"]
            if "_snippets/prerequisites/" not in source and not page.is_relative_to(docs / "_snippets/prerequisites"):
                continue
            target = (page.parent / source).resolve()
            if not target.is_relative_to(docs) or not target.is_file():
                errors.append(f"{page.relative_to(root)}: missing or unsafe prerequisite snippet {source!r}")
            elif "{{suffix}}" in target.read_text() and not attributes.get("suffix"):
                errors.append(
                    f"{page.relative_to(root)}: supply a nonempty suffix (space or punctuation) for {source!r}"
                )
    return errors


def update(root: Path, *, check: bool) -> list[str]:
    expected = generated(root)
    errors = []
    for path, content in expected.items():
        target = root / path
        if check:
            if not target.is_file() or target.read_text() != content:
                errors.append(f"{path}: stale or missing; run just docs-prerequisites")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
    # An obsolete generated value can leave an old requirement in use even
    # after its declaration was removed or renamed.
    directory = root / OUTPUT
    for target in directory.glob("*"):
        if target.is_file() and target.relative_to(root) not in expected:
            if check:
                errors.append(f"{target.relative_to(root)}: obsolete; run just docs-prerequisites")
            else:
                target.unlink()
    return errors + check_includes(root)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail on stale values without writing files")
    args = parser.parse_args()
    try:
        errors = update(ROOT, check=args.check)
    except (OSError, KeyError, ValueError) as error:
        print(f"Prerequisite generation failed: {error}", file=sys.stderr)
        return 1
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    print("Prerequisite snippets are current" if args.check else "Generated prerequisite snippets")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
